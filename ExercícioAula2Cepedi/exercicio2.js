// 1. Área de um retângulo
let largura = 5;
let altura = 3;
let areaRetangulo = largura * altura;

// 2. Perímetro de um círculo
let raio = 4;
let perimetroCirculo = 2 * Math.PI * raio;

// 3. Média de três números
let n1 = 10;
let n2 = 8;
let n3 = 6;
let media = (n1 + n2 + n3) / 3;

// Saída dos resultados
console.log("Área do retângulo: " + areaRetangulo);
console.log("Perímetro do círculo: " + perimetroCirculo.toFixed(2));
console.log("Média dos três números: " + media.toFixed(2));
